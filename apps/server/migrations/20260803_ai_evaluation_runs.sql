CREATE TABLE IF NOT EXISTS ai_evaluation_runs (
  id VARCHAR(36) NOT NULL,
  suite VARCHAR(64) NOT NULL,
  provider VARCHAR(32) NULL,
  model VARCHAR(128) NULL,
  status ENUM('queued', 'running', 'passed', 'failed', 'error') NOT NULL DEFAULT 'queued',
  repeat_count TINYINT UNSIGNED NOT NULL DEFAULT 1,
  case_count SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  passed_case_count SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  prompt_tokens INT UNSIGNED NOT NULL DEFAULT 0,
  completion_tokens INT UNSIGNED NOT NULL DEFAULT 0,
  total_tokens INT UNSIGNED NOT NULL DEFAULT 0,
  duration_ms INT UNSIGNED NOT NULL DEFAULT 0,
  result_json JSON NULL,
  error_code VARCHAR(96) NULL,
  triggered_by VARCHAR(36) NOT NULL,
  started_at DATETIME NULL,
  finished_at DATETIME NULL,
  create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_ai_evaluation_runs_suite_time (suite, create_time),
  KEY idx_ai_evaluation_runs_status (status, create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
