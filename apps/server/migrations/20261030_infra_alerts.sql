CREATE TABLE IF NOT EXISTS infra_alerts (
  alert_key VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  channel VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  fail_streak INT UNSIGNED NOT NULL DEFAULT 0,
  pass_streak INT UNSIGNED NOT NULL DEFAULT 0,
  title VARCHAR(120) NOT NULL,
  detail VARCHAR(500) DEFAULT NULL,
  first_failed_at DATETIME DEFAULT NULL,
  opened_at DATETIME DEFAULT NULL,
  resolved_at DATETIME DEFAULT NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (alert_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
